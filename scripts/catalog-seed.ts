/// <reference types="node" />
// shortcut: @types/node comes transitively via jest; add it as a devDependency if it disappears.
// Generates supabase/seed.sql from src/content/catalog/catalog.json.
// Usage: npm run catalog:seed  →  npx supabase db push --remote --include-seed
// Idempotent: upserts every row; owner-seeded rows missing from the file become 'hidden'
// (tombstones, so offline caches drop them). Community cards (created_by set) are never touched.
import { readFileSync, writeFileSync } from 'node:fs';

import { flattenCatalog, type CatalogFile, type CatalogRows } from '../src/data/catalogFile.ts';

const root = new URL('..', import.meta.url);
const file = JSON.parse(
  readFileSync(new URL('src/content/catalog/catalog.json', root), 'utf8'),
) as CatalogFile;
const rows = flattenCatalog(file);

const lit = (v: unknown) =>
  v === null ? 'null' : typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : String(v);

function upsert(table: keyof CatalogRows): string {
  const list = rows[table] as Record<string, unknown>[];
  if (!list.length) return '';
  const cols = Object.keys(list[0]);
  const values = list.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n');
  const data = cols.filter((c) => c !== 'id');
  const set = data.map((c) => `${c} = excluded.${c}`).join(', ');
  // skip unchanged rows so updated_at (delta pull) only moves on real edits
  const old = data.map((c) => `${table}.${c}`).join(', ');
  const neu = data.map((c) => `excluded.${c}`).join(', ');
  return (
    `insert into public.${table} (${cols.join(', ')}) values\n${values}\n` +
    `on conflict (id) do update set ${set}\nwhere (${old}) is distinct from (${neu});\n`
  );
}

const ids = (table: keyof CatalogRows) => rows[table].map((r) => lit(r.id)).join(', ') || "''";
const hide = (table: 'groups' | 'members' | 'releases' | 'cards', extra = '') =>
  `update public.${table} set status = 'hidden' where status <> 'hidden'${extra} and id not in (${ids(table)});\n`;

const sql = [
  '-- GENERATED by scripts/catalog-seed.ts from src/content/catalog/catalog.json. Do not edit.',
  'begin;',
  upsert('groups'),
  upsert('members'),
  upsert('releases'),
  upsert('versions'),
  upsert('cards'),
  hide('cards', ' and created_by is null'),
  // shortcut: hides any group/member/release not in the file, including community-approved ones
  // (proposals arrive in M7); before then, scope this to owner-seeded rows.
  hide('releases'),
  hide('members'),
  hide('groups'),
  'commit;',
  '',
].join('\n');

writeFileSync(new URL('supabase/seed.sql', root), sql);
console.log(
  `seed.sql: ${rows.groups.length} groups, ${rows.members.length} members, ` +
    `${rows.releases.length} releases, ${rows.versions.length} versions, ${rows.cards.length} cards`,
);
